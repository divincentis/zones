// Bumps apps/web/src/version.ts before every production build (wired up as
// the "prebuild" npm hook, so `npm run build` runs this automatically).
//
// Version format: YYYY-MM-DD.N, e.g. 2026-09-12.1. N resets to 1 on the
// first build of a new day and increments on each subsequent same-day build.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';

const versionFile = path.resolve(import.meta.dirname, '../src/version.ts');
const today = new Date().toISOString().slice(0, 10);

let seq = 1;
if (existsSync(versionFile)) {
  const match = readFileSync(versionFile, 'utf8').match(/APP_VERSION = '(\d{4}-\d{2}-\d{2})\.(\d+)'/);
  if (match && match[1] === today) {
    seq = Number(match[2]) + 1;
  }
}

const version = `${today}.${seq}`;
writeFileSync(
  versionFile,
  `// Auto-generated by scripts/bump-version.mjs on each build. Do not edit by hand.\nexport const APP_VERSION = '${version}';\n`,
);
console.log(`[bump-version] ${version}`);
